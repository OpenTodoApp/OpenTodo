// The public roadmap page (OpenSpec change docs-1-0, design D6), generated at
// docs build from the milestone tables of ROADMAP.md and the OpenSpec state of
// each change they name, so it never goes stale:
//   archived (openspec/changes/archive/<date>-<name>/)  "Shipped in x.y"
//   a folder with some tasks checked                     "In progress (n of m)"
//   no task checked, or no folder                        "Planned"
// The version of a shipped change is the oldest release in CHANGELOG.md that
// names it, else the last release on the first release date on or after its
// archive date; a change archived after the last release is "Shipped".
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

export const START = '<!-- roadmap:start (generated by `make docs` from ROADMAP.md and openspec/; do not edit) -->'
export const END = '<!-- roadmap:end -->'

const stripLinks = (s) => s.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')

/** The milestones of ROADMAP.md's "The road to 1.0": [{ title, changes: [{ name, what }] }]. */
export function parseRoadmap(text) {
  const out = []
  let inPlan = false
  let current = null
  for (const line of text.split('\n')) {
    const h2 = /^## (.*)$/.exec(line)
    if (h2) { inPlan = /road to 1\.0/i.test(h2[1]); current = null; continue }
    if (!inPlan) continue
    const h3 = /^### (.*)$/.exec(line)
    if (h3) { current = { title: stripLinks(h3[1]).trim(), changes: [] }; out.push(current); continue }
    if (!current || !line.startsWith('|')) continue
    const cells = line.split('|').slice(1, -1).map((c) => c.trim())
    const name = /`([a-z0-9-]+)`/.exec(cells[0] ?? '')?.[1]
    if (!name || cells.length < 2) continue
    const what = stripLinks(cells[1]).replace(/^\*\*[^*]+\*\*\s*/, '').trim()
    current.changes.push({ name, what })
  }
  return out.filter((m) => m.changes.length)
}

/** The releases of CHANGELOG.md, oldest first: [{ version, date, text }]. */
export function parseReleases(changelog) {
  const out = []
  const parts = changelog.split(/^## /m).slice(1)
  for (const p of parts) {
    const m = /^\[(\d+\.\d+\.\d+)\]\s*-\s*(\d{4}-\d{2}-\d{2})/.exec(p)
    if (m) out.push({ version: m[1], date: m[2], text: p })
  }
  return out.reverse()
}

const minor = (v) => v.split('.').slice(0, 2).join('.')

/** The status text of one change. */
export function changeStatus(repoRoot, name, releases) {
  const archive = join(repoRoot, 'openspec/changes/archive')
  const archived = existsSync(archive) ? readdirSync(archive).find((d) => d.slice(11) === name && /^\d{4}-\d{2}-\d{2}-/.test(d)) : undefined
  if (archived) {
    const word = new RegExp(`(^|[^a-z0-9-])${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}($|[^a-z0-9-])`)
    const named = releases.find((r) => word.test(r.text))
    // Several releases can share a date: the last of them carried what was archived that day.
    const first = releases.find((r) => r.date >= archived.slice(0, 10))
    const dated = first && releases.filter((r) => r.date === first.date).at(-1)
    const release = named ?? dated
    return release ? `Shipped in ${minor(release.version)}` : 'Shipped'
  }
  const tasks = join(repoRoot, 'openspec/changes', name, 'tasks.md')
  if (existsSync(tasks)) {
    const text = readFileSync(tasks, 'utf8')
    const done = (text.match(/^\s*- \[[xX]\]/gm) ?? []).length
    const total = done + (text.match(/^\s*- \[ \]/gm) ?? []).length
    if (done > 0) return `In progress (${done} of ${total})`
  }
  return 'Planned'
}

/** The generated block: one table per milestone. */
export function roadmapMarkdown(repoRoot) {
  const roadmap = readFileSync(join(repoRoot, 'ROADMAP.md'), 'utf8')
  const changelog = existsSync(join(repoRoot, 'CHANGELOG.md')) ? readFileSync(join(repoRoot, 'CHANGELOG.md'), 'utf8') : ''
  const releases = parseReleases(changelog)
  const lines = [START, '']
  for (const m of parseRoadmap(roadmap)) {
    lines.push(`## ${m.title}`, '', '| Change | What | Status |', '| --- | --- | --- |')
    for (const c of m.changes) lines.push(`| \`${c.name}\` | ${c.what.replace(/[\\|]/g, '\\$&')} | ${changeStatus(repoRoot, c.name, releases)} |`)
    lines.push('')
  }
  lines.push(END)
  return lines.join('\n')
}

/** The page source with its block replaced, or null when the markers are missing. */
export function withRoadmap(src, block) {
  const a = src.indexOf('<!-- roadmap:start')
  const b = src.indexOf(END)
  if (a < 0 || b < a) return null
  return src.slice(0, a) + block + src.slice(b + END.length)
}
