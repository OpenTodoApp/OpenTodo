// The keyboard guide's tables, generated from the app's shortcut rows so the `?`
// overlay and docs/keyboard.md never disagree (OpenSpec change
// `user-documentation`, design D9).
//
// TODO(user-documentation task 2.1): the rows move to web/src/lib/shortcuts.ts
// with an explicit section per row. Until then this module reads them, read-only,
// from the array literals in web/src/app/ShortcutHelp.tsx and sorts them into
// sections by the context written in the key column. Replace `loadShortcuts`
// with an import of the data module and drop the parser and `sectionFor`.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

export const START = '<!-- shortcuts:start (generated by `make docs` from the app; do not edit) -->'
export const END = '<!-- shortcuts:end -->'

/** Parses `const <name>: [string, string][] = [ ['k', 'd'], … ]` out of TSX source. */
export function parseRows(src, name) {
  const at = src.indexOf(`const ${name}`)
  if (at < 0) return []
  const open = src.indexOf('= [', at)
  // The array ends at the first line that is only "]" (two-space indent in the component).
  const close = src.indexOf('\n  ]', open)
  const body = src.slice(open + 3, close)
  const rows = []
  const str = String.raw`'((?:[^'\\]|\\.)*)'`
  const re = new RegExp(String.raw`\[\s*${str}\s*,\s*${str}\s*\]`, 'g')
  for (let m; (m = re.exec(body));) rows.push([unescape(m[1]), unescape(m[2])])
  return rows
}
const unescape = (s) => s.replace(/\\(.)/g, '$1')

/** The overlay's rows: { rows, quickAdd } from the app source. */
export function loadShortcuts(repoRoot) {
  const src = readFileSync(join(repoRoot, 'web/src/app/ShortcutHelp.tsx'), 'utf8')
  return { rows: parseRows(src, 'rows'), quickAdd: parseRows(src, 'quickAdd') }
}

const SECTIONS = [
  ['everywhere', 'Everywhere'],
  ['go', 'Go to a view'],
  ['tasks', 'Tasks in a list'],
  ['board', 'Board'],
  ['calendar', 'Day and Week calendar'],
  ['filter', 'Filter, saved views and dashboards'],
  ['trash', 'Trash and projects'],
  ['comments', 'Comments and notes'],
  ['settings', 'Settings'],
]

/** Section of one overlay row, from the context its key column names. */
export function sectionFor([key, desc]) {
  if (/^g then/.test(key)) return key.includes('Tab') ? 'settings' : 'go'
  if (/\((board)\)/.test(key)) return 'board'
  if (/calendar|placing/.test(key)) return 'calendar'
  if (/Filter|filter query|saved view|dashboard/.test(key)) return 'filter'
  if (/Trash|after completing/.test(key) || /^m$/.test(key)) return 'trash'
  if (/comment|notes|^Shift\+C$|^Shift\+H/.test(key)) return 'comments'
  if (/invitation|on a user/.test(key) || /^Settings/.test(desc)) return 'settings'
  if (/^(q|\?|Esc|Shift\+V)$/.test(key)) return 'everywhere'
  return 'tasks'
}

// Key column as <kbd> elements: "g then i / t" → <kbd>g</kbd> then <kbd>i</kbd> / <kbd>t</kbd>.
// A context in parentheses ("(board)", "(in the Trash)") is split off: the
// board and calendar sections already name theirs, the others lead the description.
export function splitContext(key) {
  const m = /^(.*?)\s*\(([^()]*)\)$/.exec(key)
  if (!m || !m[1] || m[2].includes(':')) return { keys: key, context: '' }
  return { keys: m[1], context: /^(board|calendar|placing)$/.test(m[2]) ? '' : m[2] }
}

export function keysHtml(keys, { literal = false } = {}) {
  if (literal) return `<code>${esc(keys)}</code>`
  if (/^Today, Upcoming/.test(keys)) return esc(keys)
  const note = /^(.*?) (\([^()]*:[^()]*\))$/.exec(keys)
  if (note) return `${keysHtml(note[1])} ${esc(note[2])}`
  const parts = keys.split(/( \/ | then |, | · | – |–(?=\d))/)
  return parts.map((p, i) => (i % 2 === 1 ? esc(p) : p.trim() ? `<kbd>${esc(p.trim())}</kbd>` : '')).join('')
}

function row(key, desc) {
  const { keys, context } = splitContext(key)
  const lower = /^Settings/.test(desc) ? desc : desc[0].toLowerCase() + desc.slice(1)
  const d = context ? `${context[0].toUpperCase()}${context.slice(1)}: ${lower}` : desc
  return `| ${keysHtml(keys)} | ${esc(d)} |`
}
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '&#124;')

/** The generated Markdown block between START and END. */
export function shortcutsMarkdown({ rows, quickAdd }) {
  const by = new Map(SECTIONS.map(([id]) => [id, []]))
  for (const r of rows) by.get(sectionFor(r)).push(r)
  const out = [START, '']
  for (const [id, title] of SECTIONS) {
    const list = by.get(id)
    if (!list.length) continue
    out.push(`### ${title}`, '', '| Keys | What it does |', '| --- | --- |')
    for (const [k, d] of list) out.push(row(k, d))
    out.push('')
  }
  out.push('### Quick add syntax', '', '| Type | What it does |', '| --- | --- |')
  for (const [k, d] of quickAdd) out.push(/^Backspace/.test(k) ? row(k, d) : `| ${keysHtml(k, { literal: true })} | ${esc(d)} |`)
  out.push('', END)
  return out.join('\n')
}

/** docs/keyboard.md with its generated block replaced; null when the markers are missing. */
export function withShortcuts(markdown, block) {
  const a = markdown.indexOf(START.slice(0, 22))
  const b = markdown.indexOf(END)
  if (a < 0 || b < 0) return null
  return markdown.slice(0, a) + block + markdown.slice(b + END.length)
}
