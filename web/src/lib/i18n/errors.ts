/**
 * The message to show for an API error: in English the server's own message
 * (it can name the field), in another language the translated message for the
 * code; an unknown code shows the server's message verbatim.
 */
export function errorMessage(code: string | undefined, fallback: string): string {
  const source = code ? ERROR_MESSAGES[code] : undefined
  if (!source) return fallback
  if (activeLanguage() === 'en' && fallback) return fallback
  return t(source)
}
