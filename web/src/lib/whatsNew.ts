// What's new (OpenSpec `whats-new`, design D2): two device-local flags, the same kind as the
// Vim preference. Nothing here is an op and nothing is sent to the server, so the marks do not
// sync: a second device shows the dot until its own card is opened.
//
//   ot:news-notify  "1" or absent: version notices on; "0": off.
//   ot:news-seen    the version this device last read What's new for.
import index from '../generated/newsIndex.json'
import { createStoredValue } from './deviceStorage'

export const NEWS_NOTIFY_KEY = 'ot:news-notify'
export const NEWS_SEEN_KEY = 'ot:news-seen'

/** The versions that have an entry, newest first, and the newest one (generated by scripts/news-build.mjs). */
export const NEWS_VERSIONS: readonly string[] = index.versions
export const NEWS_LATEST: string | null = index.latest

/** Version notices on this device (default on). */
export const newsNotices = createStoredValue<boolean>(NEWS_NOTIFY_KEY, {
  parse: (raw) => raw !== '0',
  serialize: (on) => (on ? '1' : '0'),
}, { crossTab: true })

/** The version this device last read What's new for. */
export const newsSeen = createStoredValue<string | null>(NEWS_SEEN_KEY, {
  parse: (raw) => raw,
  serialize: (version) => version,
}, { crossTab: true })

/** The dot: notices on, the server reports a version with an entry, and this device has not read it yet. */
export function newsDotShown(serverVersion: string | null, notices: boolean, seen: string | null): boolean {
  return notices && serverVersion !== null && NEWS_VERSIONS.includes(serverVersion) && serverVersion !== seen
}

/** The version that reading the card records: the server's, or the newest entry's when the server's is unknown. */
export function newsVersionToRecord(serverVersion: string | null): string | null {
  return serverVersion ?? NEWS_LATEST
}

/** The changelog of one version on GitHub, opened in a new tab only when chosen. */
export function releaseUrl(version: string): string {
  return `https://github.com/OpenTodoApp/OpenTodo/releases/tag/v${version}`
}

/** The dot, read live: it leaves as soon as this device records the version. */
export function useNewsDot(serverVersion: string | null): boolean {
  return newsDotShown(serverVersion, newsNotices.use(), newsSeen.use())
}
