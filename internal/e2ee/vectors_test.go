// The known-answer vectors in web/src/lib/e2ee.vectors.json are produced by this
// independent Go implementation of the format (Go's standard library, plus
// RFC 3394 key wrap below) and checked by both test suites: `go test` verifies
// the file, web/src/lib/crypto.test.ts verifies that the browser code produces
// and opens exactly the same bytes. Regenerate with:
//
//	go test ./internal/e2ee -run TestVectors -update
var update = flag.Bool("update", false, "rewrite the shared e2ee vectors")

const vectorsFile = "../../web/src/lib/e2ee.vectors.json"

type vectors struct {
	Comment string `json:"comment"`
	Content []struct {
		Key       string `json:"key"`
		Nonce     string `json:"nonce"`
		Entity    string `json:"entity"`
		EntityID  string `json:"entityId"`
		Field     string `json:"field"`
		Plaintext string `json:"plaintext"`
		Value     string `json:"value"`
	} `json:"content"`
	Passphrase struct {
		Passphrase string `json:"passphrase"`
		Salt       string `json:"salt"`
		Iterations int    `json:"iterations"`
		AccountKey string `json:"accountKey"`
		Wrapped    string `json:"wrapped"`
	} `json:"passphrase"`
	Recovery struct {
		Raw        string `json:"raw"`
		Text       string `json:"text"`
		AccountKey string `json:"accountKey"`
		Wrapped    string `json:"wrapped"`
	} `json:"recovery"`
	// File is an attachment envelope (OpenSpec attachments, design D8), with a
	// small chunk size so the vector has several chunks.
	File struct {
		Key       string `json:"key"`
		ID        string `json:"id"`
		Prefix    string `json:"prefix"`
		ChunkSize int    `json:"chunkSize"`
		Plaintext string `json:"plaintext"`
		Envelope  string `json:"envelope"`
	} `json:"file"`
}

// sealFile is the OTAT1 attachment envelope: header, then each chunk sealed with
// nonce = prefix || index (3 bytes) || final flag, AAD = "attachment\0"+id+"\0" || header.
func sealFile(key, prefix []byte, id string, chunkSize int, plaintext []byte) []byte {
	blk, _ := aes.NewCipher(key)
	gcm, _ := cipher.NewGCM(blk)
	header := append([]byte("OTAT1"), 0, 0, 0, 0)
	binary.BigEndian.PutUint32(header[5:], uint32(chunkSize))
	header = append(header, prefix...)
	aad := append([]byte("attachment\x00"+id+"\x00"), header...)
	out := append([]byte(nil), header...)
	for i := 0; ; i++ {
		end := min((i+1)*chunkSize, len(plaintext))
		final := end == len(plaintext)
		nonce := append(append([]byte(nil), prefix...), byte(i>>16), byte(i>>8), byte(i), 0)
		if final {
			nonce[11] = 1
		}
		out = gcm.Seal(out, nonce, plaintext[i*chunkSize:end], aad)
		if final {
			return out
		}
	}
}

// aesKeyWrap is RFC 3394 key wrap with the default IV.
func aesKeyWrap(kek, key []byte) []byte {
	b, err := aes.NewCipher(kek)
	if err != nil {
		panic(err)
	}
	n := len(key) / 8
	a := []byte{0xA6, 0xA6, 0xA6, 0xA6, 0xA6, 0xA6, 0xA6, 0xA6}
	r := make([][]byte, n)
	for i := range r {
		r[i] = append([]byte(nil), key[i*8:(i+1)*8]...)
	}
	buf := make([]byte, 16)
	for j := 0; j < 6; j++ {
		for i := 0; i < n; i++ {
			copy(buf, a)
			copy(buf[8:], r[i])
			b.Encrypt(buf, buf)
			t := uint64(n*j + i + 1)
			binary.BigEndian.PutUint64(a, binary.BigEndian.Uint64(buf[:8])^t)
			copy(r[i], buf[8:])
		}
	}
	out := append([]byte(nil), a...)
	for _, x := range r {
		out = append(out, x...)
	}
	return out
}

func seq(start byte, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

func sealValue(key, nonce []byte, entity, id, field, plaintext string) string {
	blk, _ := aes.NewCipher(key)
	gcm, _ := cipher.NewGCM(blk)
	aad := []byte(entity + "\x00" + id + "\x00" + field)
	ct := gcm.Seal(nil, nonce, []byte(plaintext), aad)
	return PrefixV1 + base64.RawURLEncoding.EncodeToString(append(append([]byte(nil), nonce...), ct...))
}

func recoveryText(raw []byte) string {
	enc := base32.StdEncoding.WithPadding(base32.NoPadding)
	sum := sha256.Sum256(raw)
	text := enc.EncodeToString(raw) + enc.EncodeToString(sum[:3])[:4]
	var groups []string
	for i := 0; i < len(text); i += 4 {
		groups = append(groups, text[i:i+4])
	}
	return strings.Join(groups, "-")
}

func generate(t *testing.T) vectors {
	var v vectors
	v.Comment = "Generated by internal/e2ee/vectors_test.go (Go standard library); verified by crypto.test.ts. Hex unless noted; value/wrapped are the wire format."
	key := seq(0x00, 32)
	for _, c := range []struct {
		nonce                 byte
		entity, id, field, pt string
	}{
		{0xa0, "task", "t1", "title", "Dentist"},
		{0xb0, "task", "6b9f2c1e-3d4a-4f8b-9c2d-1e3f4a5b6c7d", "description", "Ask about the crown — café, \U0001F9B7"},
		{0xc0, "label", "l1", "name", ""},
		// A custom field string value (OpenSpec custom-fields, design D4).
		{0xe0, "task", "t1", "fields.f1", "Acme"},
	} {
		nonce := seq(c.nonce, 12)
		v.Content = append(v.Content, struct {
			Key       string `json:"key"`
			Nonce     string `json:"nonce"`
			Entity    string `json:"entity"`
			EntityID  string `json:"entityId"`
			Field     string `json:"field"`
			Plaintext string `json:"plaintext"`
			Value     string `json:"value"`
		}{hex.EncodeToString(key), hex.EncodeToString(nonce), c.entity, c.id, c.field, c.pt, sealValue(key, nonce, c.entity, c.id, c.field, c.pt)})
	}
	dek := seq(0x40, 32)
	v.Passphrase.Passphrase = "correct horse battery staple"
	salt := seq(0x10, 16)
	v.Passphrase.Salt = hex.EncodeToString(salt)
	v.Passphrase.Iterations = 1000
	v.Passphrase.AccountKey = hex.EncodeToString(dek)
	kek, err := pbkdf2.Key(sha256.New, v.Passphrase.Passphrase, salt, v.Passphrase.Iterations, 32)
	if err != nil {
		t.Fatal(err)
	}
	v.Passphrase.Wrapped = base64.RawURLEncoding.EncodeToString(aesKeyWrap(kek, dek))
	raw := seq(0x80, 32)
	v.Recovery.Raw = hex.EncodeToString(raw)
	v.Recovery.Text = recoveryText(raw)
	v.Recovery.AccountKey = hex.EncodeToString(dek)
	rkek, err := hkdf.Key(sha256.New, raw, make([]byte, 32), "opentodo/e2ee/recovery-kek/v1", 32)
	if err != nil {
		t.Fatal(err)
	}
	v.Recovery.Wrapped = base64.RawURLEncoding.EncodeToString(aesKeyWrap(rkek, dek))
	v.File.Key = hex.EncodeToString(key)
	v.File.ID = "a1"
	v.File.Prefix = hex.EncodeToString(seq(0xd0, 8))
	v.File.ChunkSize = 16
	v.File.Plaintext = "The quick brown fox jumps over the lazy dog"
	v.File.Envelope = hex.EncodeToString(sealFile(key, seq(0xd0, 8), v.File.ID, v.File.ChunkSize, []byte(v.File.Plaintext)))
	return v
}

func TestVectors(t *testing.T) {
	want := generate(t)
	if *update {
		b, _ := json.MarshalIndent(want, "", "  ")
		if err := os.WriteFile(vectorsFile, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	raw, err := os.ReadFile(vectorsFile)
	if err != nil {
		t.Fatalf("read vectors (run with -update to create): %v", err)
	}
	var got vectors
	if err := json.Unmarshal(raw, &got); err != nil {
		t.Fatal(err)
	}
	a, _ := json.Marshal(got)
	b, _ := json.Marshal(want)
	if string(a) != string(b) {
		t.Fatalf("vectors file differs from the Go implementation; regenerate with -update")
	}
	// RFC 3394 section 4.6 (256-bit KEK, 256-bit key) checks the wrap helper itself.
	kek, _ := hex.DecodeString("000102030405060708090A0B0C0D0E0F101112131415161718191A1B1C1D1E1F")
	key, _ := hex.DecodeString("00112233445566778899AABBCCDDEEFF000102030405060708090A0B0C0D0E0F")
	if w := strings.ToUpper(hex.EncodeToString(aesKeyWrap(kek, key))); w != "28C9F404C4B810F4CBCCB35CFB87F8263F5786E2D80ED326CBC7F0E71A99F43BFB988B9B7A02DD21" {
		t.Fatalf("AES-KW = %s", w)
	}
	// Every content vector is recognised as ciphertext; tampering fails to open.
	for _, c := range got.Content {
		if !IsCiphertext(c.Value) || !IsContentField(c.Entity, c.Field) {
			t.Fatalf("%s.%s: %q", c.Entity, c.Field, c.Value)
		}
		k, _ := hex.DecodeString(c.Key)
		blk, _ := aes.NewCipher(k)
		gcm, _ := cipher.NewGCM(blk)
		body, _ := base64.RawURLEncoding.DecodeString(strings.TrimPrefix(c.Value, PrefixV1))
		if _, err := gcm.Open(nil, body[:12], body[12:], []byte(c.Entity+"\x00"+c.EntityID+"\x00other")); err == nil {
			t.Fatal("a value opened under another field's binding")
		}
	}
}
