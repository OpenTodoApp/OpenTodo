// The v1 surface snapshot (OpenSpec change `stability-contract`, design D1;
// docs/stability.md). testdata/v1_surface.json records what 1.x promises to
// keep: every /api/v1/ route with its policy, statuses, request and response
// fields; the error codes with their statuses; the op schema; the export
// format; the MCP tools; the `ot` commands. TestV1SurfaceIsAdditive fails when
// anything recorded is gone or changed, and when something new is not
// recorded yet. `-update` records the new entries and never removes or
// changes one.

var updateSurface = flag.Bool("update", false, "add new entries to testdata/v1_surface.json (never removes or changes one)")

const surfaceFile = "testdata/v1_surface.json"

// surfaceSep joins the parts of a flattened surface path.
const surfaceSep = " › "

const surfaceAbout = "The v1 surface (OpenSpec change stability-contract, docs/stability.md): what every 1.x release keeps. " +
	"Generated by internal/httpapi TestV1SurfaceIsAdditive; `go test ./internal/httpapi -run TestV1SurfaceIsAdditive -update` adds new entries " +
	"and never removes or changes one. Removing or changing an entry needs a new major version."

// buildSurface builds the current v1 surface as nested JSON values.
func buildSurface(t *testing.T) map[string]any {
	t.Helper()
	pkgs := loadStatic(t)
	routes := surfaceRoutes(t, staticRoutes(pkgs))
	return map[string]any{
		"about":  surfaceAbout,
		"routes": routes,
		"errors": surfaceErrors(t, errorStatuses(pkgs)),
		"ops":    toAny(opsync.SchemaKinds()),
		"export": surfaceExport(t),
		"mcp":    surfaceMCP(t),
		"cli":    surfaceCLI(t),
	}
}

// surfaceRoutes lists the /api/v1/ routes of the route table: policy,
// deprecation, success statuses and fields. The generic collection routes are
// also listed per collection with the collection's fields.
func surfaceRoutes(t *testing.T, static map[string]*staticRoute) map[string]any {
	t.Helper()
	out := map[string]any{}
	table := map[string]routePolicy{}
	for _, demo := range []bool{false, true} {
		for _, e := range routeTableOf(t, demo) {
			table[e.pattern] = e.policy
		}
	}
	for pattern, p := range table {
		if !strings.Contains(pattern, " /api/v1/") {
			continue
		}
		r := map[string]any{"policy": policyName(p)}
		if d := p.Deprecation; d != nil {
			r["deprecated"] = fmt.Sprintf("since %s, sunset %s, use %s", d.Since.UTC().Format("2006-01-02"), d.Sunset.UTC().Format("2006-01-02"), d.Replacement)
		}
		if s := static[pattern]; s != nil {
			if len(s.statuses) > 0 {
				r["statuses"] = slices.Sorted(maps.Keys(s.statuses))
			}
			if len(s.request) > 0 {
				r["request"] = toAny(s.request)
			}
			if len(s.response) > 0 {
				r["response"] = toAny(s.response)
			}
		}
		out[pattern] = r
	}
	for pattern, r := range collectionRoutes(t, table) {
		if _, explicit := out[pattern]; !explicit {
			out[pattern] = r
		}
	}
	return out
}

// policyName is a route policy as one stable word with its modifiers. The demo
// deny list is not part of the contract (it concerns the public demo only).
func policyName(p routePolicy) string {
	var b strings.Builder
	switch {
	case p.Kind == httpx.KindPublic:
		b.WriteString("public")
	case p.Role == httpx.OwnerRole:
		b.WriteString("owner-only")
	case p.Role == httpx.AdminRole:
		b.WriteString("admins-only")
	default:
		b.WriteString("signed-in")
	}
	switch p.Tokens {
	case httpx.TokensFull:
		b.WriteString(".full-tokens")
	case httpx.TokensAdmin:
		b.WriteString(".credential")
	case httpx.TokensNone:
		b.WriteString(".session-only")
	}
	if p.Fresh {
		b.WriteString(".recent")
	}
	return b.String()
}

// surfaceErrors is every error code with its statuses: the codes the web
// client knows (web/src/lib/i18n/server-error-codes.json) and every code the
// route packages answer with a constant status.
func surfaceErrors(t *testing.T, found map[string][]string) map[string]any {
	t.Helper()
	raw, err := os.ReadFile("../../web/src/lib/i18n/server-error-codes.json")
	if err != nil {
		t.Fatal(err)
	}
	var known []string
	if err := json.Unmarshal(raw, &known); err != nil {
		t.Fatal(err)
	}
	// Each code is a set: "listed" plus every status it is answered with, so a
	// status found later is an addition.
	out := map[string]any{}
	for _, c := range known {
		out[c] = []string{"listed"}
	}
	for c, sts := range found {
		out[c] = append([]string{"listed"}, sts...)
	}
	return out
}

// toAny converts a nested map of strings to JSON values.
func toAny[V any](m map[string]V) map[string]any {
	out := make(map[string]any, len(m))
	for k, v := range m {
		switch v := any(v).(type) {
		case map[string]string:
			out[k] = toAny(v)
		default:
			out[k] = v
		}
	}
	return out
}

// ---- flattening and comparing ----

// flattenSurface turns nested JSON values into path → value. A list of strings
// becomes one path per element with an empty value (a set).
func flattenSurface(v any, prefix string, out map[string]string) {
	switch v := v.(type) {
	case map[string]any:
		for k, sub := range v {
			flattenSurface(sub, joinPath(prefix, k), out)
		}
	case []any:
		for _, el := range v {
			flattenSurface("", joinPath(prefix, fmt.Sprint(el)), out)
		}
	case []string:
		for _, el := range v {
			out[joinPath(prefix, el)] = ""
		}
	case string:
		out[prefix] = v
	case nil:
		out[prefix] = "null"
	default:
		out[prefix] = fmt.Sprint(v)
	}
}

func joinPath(prefix, k string) string {
	if prefix == "" {
		return k
	}
	return prefix + surfaceSep + k
}

// unflattenSurface is the inverse of flattenSurface: a node whose children all
// have empty values is a sorted list.
func unflattenSurface(flat map[string]string) map[string]any {
	type node struct {
		val      *string
		children map[string]*node
	}
	root := &node{children: map[string]*node{}}
	for path, v := range flat {
		n := root
		for _, part := range strings.Split(path, surfaceSep) {
			if n.children == nil {
				n.children = map[string]*node{}
			}
			c := n.children[part]
			if c == nil {
				c = &node{}
				n.children[part] = c
			}
			n = c
		}
		v := v
		n.val = &v
	}
	var build func(n *node) any
	build = func(n *node) any {
		if len(n.children) == 0 {
			if n.val == nil {
				return ""
			}
			return *n.val
		}
		set := true
		for _, c := range n.children {
			if len(c.children) > 0 || c.val == nil || *c.val != "" {
				set = false
			}
		}
		if set {
			return slices.Sorted(maps.Keys(n.children))
		}
		m := map[string]any{}
		for k, c := range n.children {
			m[k] = build(c)
		}
		return m
	}
	return build(root).(map[string]any)
}

// surfaceDiff is how the current surface differs from the snapshot.
type surfaceDiff struct {
	missing []string // in the snapshot, gone now: a removal or rename
	changed []string // a different type, status, policy or exit code
	added   []string // new, not in the snapshot yet
}

func (d surfaceDiff) empty() bool { return len(d.missing)+len(d.changed)+len(d.added) == 0 }

// compareSurface compares two flattened surfaces. The about text is not part
// of the contract.
func compareSurface(snapshot, current map[string]string) surfaceDiff {
	var d surfaceDiff
	for path, was := range snapshot {
		if path == "about" {
			continue
		}
		now, ok := current[path]
		switch {
		case !ok:
			d.missing = append(d.missing, path+" is gone (removed or renamed)")
		case now != was && strings.HasSuffix(was, "?") && now == strings.TrimSuffix(was, "?"):
			d.changed = append(d.changed, path+": became required")
		case now != was:
			d.changed = append(d.changed, fmt.Sprintf("%s: was %q, now %q", path, was, now))
		}
	}
	for path := range current {
		if _, ok := snapshot[path]; !ok && path != "about" {
			d.added = append(d.added, path)
		}
	}
	sort.Strings(d.missing)
	sort.Strings(d.changed)
	sort.Strings(d.added)
	return d
}

// mergeSurface is the snapshot plus the new entries of current: -update adds,
// it never removes or changes an entry.
func mergeSurface(snapshot, current map[string]string) map[string]string {
	out := maps.Clone(snapshot)
	for path, v := range current {
		if _, ok := out[path]; !ok {
			out[path] = v
		}
	}
	out["about"] = surfaceAbout
	return out
}

func readSurfaceFile(t *testing.T) map[string]string {
	t.Helper()
	raw, err := os.ReadFile(surfaceFile)
	if os.IsNotExist(err) {
		return map[string]string{}
	}
	if err != nil {
		t.Fatal(err)
	}
	var v map[string]any
	if err := json.Unmarshal(raw, &v); err != nil {
		t.Fatalf("%s: %v", surfaceFile, err)
	}
	flat := map[string]string{}
	flattenSurface(v, "", flat)
	return flat
}

func writeSurfaceFile(t *testing.T, flat map[string]string) {
	t.Helper()
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(unflattenSurface(flat)); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(surfaceFile, b.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestV1SurfaceIsAdditive: the current surface keeps every entry of the
// snapshot unchanged, and every new entry is recorded.
func TestV1SurfaceIsAdditive(t *testing.T) {
	if testing.Short() {
		t.Skip("builds the whole surface")
	}
	current := map[string]string{}
	flattenSurface(buildSurface(t), "", current)
	snapshot := readSurfaceFile(t)
	d := compareSurface(snapshot, current)
	for _, m := range d.missing {
		t.Errorf("v1 surface: %s; the v1 surface only grows (docs/stability.md)", m)
	}
	for _, c := range d.changed {
		t.Errorf("v1 surface: %s; an incompatible change needs a new major version (docs/stability.md)", c)
	}
	if len(d.added) == 0 {
		return
	}
	if *updateSurface {
		writeSurfaceFile(t, mergeSurface(snapshot, current))
		t.Logf("added %d entries to %s", len(d.added), surfaceFile)
		return
	}
	shown := d.added
	if len(shown) > 20 {
		shown = shown[:20]
	}
	t.Errorf("v1 surface: %d new entries are not in %s (first: %s); run `go test ./internal/httpapi -run TestV1SurfaceIsAdditive -update`",
		len(d.added), surfaceFile, strings.Join(shown, "; "))
}

// TestV1SurfaceBuilder: the builder finds a known route with its fields, a
// tool, a command, an op field, an error code and the export version.
func TestV1SurfaceBuilder(t *testing.T) {
	if testing.Short() {
		t.Skip("builds the whole surface")
	}
	flat := map[string]string{}
	flattenSurface(buildSurface(t), "", flat)
	for path, want := range map[string]string{
		"routes › GET /api/v1/me › policy":                          "signed-in",
		"routes › GET /api/v1/me › response › user":                 "",
		"routes › GET /api/v1/tasks/{id} › response › completed_at": "nullable_number",
		"routes › POST /api/v1/sections › request › project_id":     "id",
		"routes › POST /api/v1/tokens › policy":                     "signed-in.credential.recent",
		"routes › POST /api/v1/auth/login › request › email":        "string",
		"errors › bad_request › 400":                                "",
		"ops › task › completed_at":                                 "nullable_number",
		"export › version":                                          "1",
		"export › format":                                           "opentodo-export",
		"mcp › list_tasks › kind":                                   "read",
		"cli › commands › add › flags › project":                    "string",
		"cli › exit_codes › 2":                                      "usage",
	} {
		got, ok := flat[path]
		if !ok {
			t.Errorf("surface has no %q", path)
			continue
		}
		if want != "" && got != want {
			t.Errorf("%s = %q, want %q", path, got, want)
		}
	}
}

// TestCompareSurface: the unit cases of the additive rule.
func TestCompareSurface(t *testing.T) {
	snapshot := map[string]string{
		"routes › GET /api/v1/tasks/{id} › policy":                  "signed-in",
		"routes › GET /api/v1/tasks/{id} › response › completed_at": "nullable_number",
		"routes › POST /api/v1/tasks › request › project_id":        "string|null?",
		"routes › POST /api/v1/tasks › statuses › 201":              "",
		"errors › bad_request › 400":                                "",
		"cli › exit_codes › 2":                                      "usage",
	}
	cases := []struct {
		name   string
		change func(m map[string]string)
		want   string
	}{
		{"missing route", func(m map[string]string) {
			for k := range m {
				if strings.Contains(k, "GET /api/v1/tasks/{id}") {
					delete(m, k)
				}
			}
		}, "routes › GET /api/v1/tasks/{id} › policy is gone"},
		{"renamed field", func(m map[string]string) {
			delete(m, "routes › GET /api/v1/tasks/{id} › response › completed_at")
			m["routes › GET /api/v1/tasks/{id} › response › done_at"] = "number|null"
		}, "routes › GET /api/v1/tasks/{id} › response › completed_at is gone"},
		{"changed status", func(m map[string]string) {
			delete(m, "routes › POST /api/v1/tasks › statuses › 201")
			m["routes › POST /api/v1/tasks › statuses › 200"] = ""
		}, "routes › POST /api/v1/tasks › statuses › 201 is gone"},
		{"changed policy", func(m map[string]string) {
			m["routes › GET /api/v1/tasks/{id} › policy"] = "owner-only"
		}, `routes › GET /api/v1/tasks/{id} › policy: was "signed-in", now "owner-only"`},
		{"field becomes required", func(m map[string]string) {
			m["routes › POST /api/v1/tasks › request › project_id"] = "string|null"
		}, "routes › POST /api/v1/tasks › request › project_id: became required"},
		{"changed exit code", func(m map[string]string) {
			m["cli › exit_codes › 2"] = "server_error"
		}, `cli › exit_codes › 2: was "usage"`},
		{"unlisted new route", func(m map[string]string) {
			m["routes › GET /api/v1/objectives2 › policy"] = "signed-in"
		}, "added: routes › GET /api/v1/objectives2 › policy"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			current := maps.Clone(snapshot)
			c.change(current)
			d := compareSurface(snapshot, current)
			all := strings.Join(d.missing, "\n") + "\n" + strings.Join(d.changed, "\n") + "\nadded: " + strings.Join(d.added, "\nadded: ")
			if !strings.Contains(all, c.want) {
				t.Fatalf("diff = %s\nwant %q", all, c.want)
			}
		})
	}
	if d := compareSurface(snapshot, maps.Clone(snapshot)); !d.empty() {
		t.Fatalf("identical surfaces differ: %+v", d)
	}
	// -update only adds: a changed value keeps the snapshot's, a missing entry stays.
	current := maps.Clone(snapshot)
	current["cli › exit_codes › 2"] = "server_error"
	delete(current, "errors › bad_request › 400")
	current["routes › GET /api/v1/new › policy"] = "signed-in"
	merged := mergeSurface(snapshot, current)
	if merged["cli › exit_codes › 2"] != "usage" || merged["routes › GET /api/v1/new › policy"] != "signed-in" {
		t.Fatalf("merge = %v", merged)
	}
	if _, ok := merged["errors › bad_request › 400"]; !ok {
		t.Fatal("merge removed an entry")
	}
	// The file format round-trips.
	back := map[string]string{}
	flattenSurface(roundTrip(t, unflattenSurface(merged)), "", back)
	if d := compareSurface(merged, back); !d.empty() {
		t.Fatalf("round trip differs: %+v", d)
	}
}

func roundTrip(t *testing.T, v map[string]any) any {
	t.Helper()
	raw, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	var out any
	if err := json.Unmarshal(raw, &out); err != nil {
		t.Fatal(err)
	}
	return out
}
