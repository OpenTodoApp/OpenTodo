// The brand kit in brand/ (OpenSpec change brand-kit, design D2 and D3): the logo files people
// use outside the code, written by scripts/brand-icons.mjs from the mark (brand.svg) and the
// wordmark's outlines (wordmark.svg). Each output is either `text` (an SVG or the README) or
// `page` (markup Chromium screenshots at `width` × `height`); both receive the sources and the
// brand script's helpers, so this module imports nothing from it.

export const WORDMARK = 'web/src/ui/icons/wordmark.svg'
export const FONT = 'web/src/assets/fonts/InterVariable-latin.woff2'

const SLATE = '#0f172a'
const EMERALD = '#34d399'
const EMERALD_DARK = '#047857'
const WHITE = '#ffffff'
const TAGLINE = 'A to-do app that runs on your own server.'
const NOTE = '<!-- OpenTodo brand mark. Part of OpenTodo, AGPL-3.0 (see LICENSE). The wordmark is outlined from Inter (SIL Open Font License 1.1). -->'

/** Variants of the mark alone: tray colour, tick colour. */
const MARKS = {
  'on-light': [SLATE, EMERALD_DARK],
  'on-dark': [WHITE, EMERALD],
  black: ['#000000', '#000000'],
  white: [WHITE, WHITE],
}
/** Lockups: tray, tick, wordmark colour. */
const LOCKUPS = { 'on-light': [SLATE, EMERALD_DARK, SLATE], 'on-dark': [WHITE, EMERALD, WHITE] }
const ICON_SIZES = [16, 32, 48, 64, 128, 180, 192, 256, 512, 1024]
const MARK_SIZES = [256, 512, 1024]
// The lockup's viewBox: the mark on 0–24, the wordmark at 0.625 of its 24-unit source from x 29,
// its cap height centred on the mark's centre line (D2).
const LOCKUP_W = 106.5
const WORD_SCALE = 0.625
const WORD_Y = 6.2

const wordPath = (wordmark) => /<path d="([^"]+)"/.exec(wordmark)[1]
const svgDoc = (viewBox, body, size = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${size} role="img"><title>OpenTodo</title>${NOTE}${body}</svg>\n`
const strokes = ([tray, tick], h, source) => {
  const [t, k] = h.symbolPaths(source, 'mono')
  // The mono symbol's own group (stroke width, caps, joins), so the kit follows the source.
  return `<g ${h.symbolGroup(source, 'mono')}><path d="${t}" stroke="${tray}"/><path d="${k}" stroke="${tick}"/></g>`
}
const markSvg = (v, source, h) => svgDoc('0 0 24 24', strokes(MARKS[v], h, source))
function lockupSvg(v, source, wordmark, h) {
  const [tray, tick, word] = LOCKUPS[v]
  return svgDoc(`0 0 ${LOCKUP_W} 24`, `${strokes([tray, tick], h, source)}<path transform="translate(29 ${WORD_Y}) scale(${WORD_SCALE})" d="${wordPath(wordmark)}" fill="${word}"/>`)
}
/** A standalone SVG as a page of exactly `w` × `h` pixels. */
const asPage = (svg, w, h) => svg.replace('<svg ', `<svg width="${w}" height="${h}" `)

/**
 * A banner of `w` × `h`: the lockup on dark, centred on the slate rounded rectangle, for a
 * store that shows a wide logo on light and dark pages alike (the Home Assistant add-on).
 */
export function bannerPage(w, h, source, wordmark, help) {
  const lockH = Math.round(h * 0.4)
  const lockW = Math.round((lockH * LOCKUP_W) / 24)
  const lockup = asPage(lockupSvg('on-dark', source, wordmark, help), lockW, lockH)
  return `<!doctype html><style>html,body{margin:0;width:${w}px;height:${h}px;background:transparent}
div{width:${w}px;height:${h}px;border-radius:${Math.round(h * 0.18)}px;background:${SLATE};display:flex;align-items:center;justify-content:center}svg{display:block}</style><body><div>${lockup}</div></body>`
}

/** A social image: the colour icon, the outlined wordmark and the tagline in the bundled Inter. */
function socialPage(w, h, light, source, wordmark, help, font) {
  const bg = light ? '#f8fafc' : SLATE
  const word = light ? SLATE : WHITE
  const sub = light ? '#475569' : '#cbd5e1'
  const bar = light ? '<div style="position:absolute;inset:0 0 auto 0;height:10px;background:#059669"></div>' : ''
  const icon = asPage(help.symbolSvg(source, 'colour'), 168, 168)
  const name = `<svg width="${122.34 * 4}" height="96" viewBox="0 0 122.34 24"><path d="${wordPath(wordmark)}" fill="${word}"/></svg>`
  return `<!doctype html><style>@font-face{font-family:InterBrand;src:url(data:font/woff2;base64,${font.toString('base64')}) format('woff2');font-weight:100 900}
html,body{margin:0;width:${w}px;height:${h}px;background:${bg}}body{position:relative;display:flex;align-items:center;justify-content:center;gap:48px;font-family:InterBrand}
p{margin:14px 0 0 2px;font-size:40px;line-height:1;color:${sub};font-weight:400}</style><body>${bar}${icon}<div>${name}<p>${TAGLINE}</p></div></body>`
}

function readme() {
  return `# OpenTodo brand kit

The OpenTodo logo for use outside the code: slides, a README, an avatar, a press mention. Every file here is generated by \`make brand-icons\` (\`scripts/brand-icons.mjs\`) from \`web/src/ui/icons/brand.svg\` (the mark) and \`web/src/ui/icons/wordmark.svg\` (the name, outlined from Inter SemiBold); don't edit or add files by hand, a test fails on it. The mark is part of OpenTodo and under the AGPL-3.0 (see \`LICENSE\`); the wordmark's glyph outlines come from Inter, under the SIL Open Font License 1.1.

Colours: slate \`${SLATE}\`, emerald \`${EMERALD}\` (on dark) and \`${EMERALD_DARK}\` (on light), white \`${WHITE}\`.

| File | Use |
|---|---|
| \`svg/mark-colour.svg\`, \`png/icon-*.png\` | The app icon: the mark on the slate rounded square, 16 to 1024 px |
| \`svg/mark-colour-square.svg\`, \`png/avatar-512.png\` | The square without rounding, for avatars the platform crops itself (GitHub organisation, Discord, X, Buy Me a Coffee, the Google Play icon, stores) |
| \`svg/mark-on-light.svg\`, \`png/mark-on-light-*.png\` | The mark alone on a light background: slate tray, dark emerald tick |
| \`svg/mark-on-dark.svg\`, \`png/mark-on-dark-*.png\` | The mark alone on a dark background: white tray, emerald tick |
| \`svg/mark-black.svg\`, \`svg/mark-white.svg\` and their PNGs | One colour, for print, stamps and embossing |
| \`svg/lockup-on-light.svg\`, \`svg/lockup-on-dark.svg\` and their PNGs | The mark with "OpenTodo" beside it (headers, slides, a README) |
| \`png/github-social-preview-1280x640.png\` | GitHub → Settings → Social preview |
| \`png/og-default-1200x630.png\` | A default social card for link previews |
| \`png/play-feature-graphic-1024x500.png\` | Google Play → Store listing → Feature graphic (opaque, no alpha) |

Keep the tray and the tick in their two colours except in the one-colour files, never put the mark inside a checkbox or a closed square, and keep clear space of at least the tray's height around it.
`
}

/** Every file of the kit, as brand-icons.mjs outputs. */
export const KIT_OUTPUTS = [
  { path: 'brand/README.md', text: () => readme() },
  ...Object.keys(MARKS).map((v) => ({ path: `brand/svg/mark-${v}.svg`, text: (s, _w, h) => markSvg(v, s, h) })),
  { path: 'brand/svg/mark-colour.svg', text: (s, _w, h) => h.symbolSvg(s, 'colour', { title: true }) },
  { path: 'brand/svg/mark-colour-square.svg', text: (s, _w, h) => h.symbolSvg(s, 'colour', { title: true, full: true }) },
  ...Object.keys(LOCKUPS).map((v) => ({ path: `brand/svg/lockup-${v}.svg`, text: (s, w, h) => lockupSvg(v, s, w, h) })),
  ...ICON_SIZES.map((n) => ({ path: `brand/png/icon-${n}.png`, width: n, height: n, page: (s, _w, h) => asPage(h.symbolSvg(s, 'colour'), n, n) })),
  { path: 'brand/png/avatar-512.png', width: 512, height: 512, page: (s, _w, h) => asPage(h.symbolSvg(s, 'colour', { full: true }), 512, 512) },
  ...Object.keys(MARKS).flatMap((v) => MARK_SIZES.map((n) => ({ path: `brand/png/mark-${v}-${n}.png`, width: n, height: n, page: (s, _w, h) => asPage(markSvg(v, s, h), n, n) }))),
  ...Object.keys(LOCKUPS).flatMap((v) => [8, 16].map((k) => {
    const [w, ht] = [LOCKUP_W * k, 24 * k]
    return { path: `brand/png/lockup-${v}-${w}x${ht}.png`, width: w, height: ht, page: (s, wm, h) => asPage(lockupSvg(v, s, wm, h), w, ht) }
  })),
  { path: 'brand/png/github-social-preview-1280x640.png', width: 1280, height: 640, page: (s, w, h, f) => socialPage(1280, 640, false, s, w, h, f) },
  { path: 'brand/png/og-default-1200x630.png', width: 1200, height: 630, page: (s, w, h, f) => socialPage(1200, 630, true, s, w, h, f) },
  // Google Play's feature graphic (brand-assets-everywhere): 1024 × 500, no alpha channel.
  { path: 'brand/png/play-feature-graphic-1024x500.png', width: 1024, height: 500, opaque: true, page: (s, w, h, f) => socialPage(1024, 500, false, s, w, h, f) },
]
