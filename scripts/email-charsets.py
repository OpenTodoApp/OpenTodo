#!/usr/bin/env python3
# Writes internal/email/charsets_gen.go: the upper half (0x80-0xFF) of the
# single-byte mail charsets OpenTodo decodes, from Python's codec tables.
# Usage: python3 scripts/email-charsets.py > internal/email/charsets_gen.go && gofmt -w internal/email/charsets_gen.go
CHARSETS = [
    # (Go name, codec, labels)
    ("cp1250", "cp1250", ["windows-1250", "cp1250", "x-cp1250"]),
    ("iso88592", "iso8859_2", ["iso-8859-2", "iso8859-2", "iso_8859-2", "latin2", "latin-2", "l2"]),
    ("cp1251", "cp1251", ["windows-1251", "cp1251", "x-cp1251"]),
    ("koi8r", "koi8_r", ["koi8-r", "koi8r"]),
    ("koi8u", "koi8_u", ["koi8-u", "koi8u"]),
    ("iso88595", "iso8859_5", ["iso-8859-5", "iso8859-5", "iso_8859-5", "cyrillic"]),
    ("cp1253", "cp1253", ["windows-1253", "cp1253"]),
    ("iso88597", "iso8859_7", ["iso-8859-7", "iso8859-7", "iso_8859-7", "greek"]),
    ("cp1254", "cp1254", ["windows-1254", "cp1254"]),
    ("iso88599", "iso8859_9", ["iso-8859-9", "iso8859-9", "iso_8859-9", "latin5", "l5"]),
    ("cp1257", "cp1257", ["windows-1257", "cp1257"]),
    ("iso885913", "iso8859_13", ["iso-8859-13", "iso8859-13", "latin7"]),
    ("iso885916", "iso8859_16", ["iso-8859-16", "iso8859-16", "latin10"]),
]
print("// Code generated by scripts/email-charsets.py; DO NOT EDIT.\n")
print("package email\n")
print("// singleByte maps a charset label to the runes of its bytes 0x80-0xFF;")
print("// U+FFFD marks a byte the charset leaves undefined.")
print("var singleByte = map[string]*[128]rune{")
for name, _, labels in CHARSETS:
    for l in labels:
        print(f'\t"{l}": &{name},')
print("}\n")
for name, codec, _ in CHARSETS:
    runes = []
    for b in range(0x80, 0x100):
        try:
            ch = bytes([b]).decode(codec)
        except UnicodeDecodeError:
            ch = "�"
        runes.append("0x%04X" % ord(ch))
    print(f"var {name} = [128]rune{{")
    for i in range(0, 128, 8):
        print("\t" + ", ".join(runes[i:i+8]) + ",")
    print("}\n")
