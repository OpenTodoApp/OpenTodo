#!/usr/bin/env node
// Generates internal/importer/windowszones.go from CLDR's windowsZones.xml
// (OpenSpec change more-importers, design D5): Microsoft Graph names time zones
// by their Windows id ("Pacific Standard Time"); the importer maps them to IANA
// names with this table. Only the territory "001" rows are kept (the zone CLDR
// recommends for each Windows id).
//
//   node scripts/windows-zones.mjs <path to windowsZones.xml>
//
// The XML lives at https://github.com/unicode-org/cldr, common/supplemental/windowsZones.xml.
// Download it first; this script makes no network request.
import { readFileSync, writeFileSync } from 'node:fs'

const src = process.argv[2]
if (!src) {
  console.error('usage: node scripts/windows-zones.mjs <windowsZones.xml>')
  process.exit(2)
}
const xml = readFileSync(src, 'utf8')
const version = xml.match(/<version number="\$Revision: *([^$ ]*) *\$"/)?.[1] ?? ''
const rows = []
for (const m of xml.matchAll(/<mapZone other="([^"]+)" territory="001" type="([^"]+)"\s*\/>/g)) rows.push([m[1], m[2]])
if (rows.length < 100) {
  console.error(`only ${rows.length} zones found; is this windowsZones.xml?`)
  process.exit(1)
}
rows.sort((a, b) => a[0].localeCompare(b[0]))
const lines = rows.map(([win, iana]) => `\t${JSON.stringify(win)}: ${JSON.stringify(iana)},`)
const out = `// Code generated by scripts/windows-zones.mjs from CLDR windowsZones.xml${version ? ` (revision ${version})` : ''}; DO NOT EDIT.

package importer

// windowsZones maps a Windows time zone id, as Microsoft Graph writes it, to
// the IANA zone CLDR recommends for it (territory 001).
var windowsZones = map[string]string{
${lines.join('\n')}
}
`
writeFileSync(new URL('../internal/importer/windowszones.go', import.meta.url), out)
console.log(`windowszones.go: ${rows.length} zones`)
