// Regenerates web/src/ui/icons/lucide.ts from an unpacked lucide-static package
// (OpenSpec change ui-primitives, design D2). Dev-only and run by hand; the build
// never downloads anything. To add an icon, add its name to
// web/src/ui/icons/names.json and run:
//
//   npm pack lucide-static@1.48.0 && tar xzf lucide-static-1.48.0.tgz
//   node scripts/icons-sync.mjs ./package
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const pkg = process.argv[2]
if (!pkg) {
  console.error('usage: node scripts/icons-sync.mjs <path to unpacked lucide-static package>')
  process.exit(2)
}
const out = new URL('../web/src/ui/icons/', import.meta.url).pathname
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version
const names = JSON.parse(readFileSync(join(out, 'names.json'), 'utf8'))
const missing = []
const entries = names.map((name) => {
  let svg
  try {
    svg = readFileSync(join(pkg, 'icons', `${name}.svg`), 'utf8')
  } catch {
    missing.push(name)
    return ''
  }
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
    .split('\n').map((l) => l.trim()).filter(Boolean).join('')
  return `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`
})
if (missing.length) {
  console.error(`not in lucide-static ${version}: ${missing.join(', ')}`)
  process.exit(1)
}
writeFileSync(join(out, 'lucide.ts'), `// Generated by scripts/icons-sync.mjs from lucide-static ${version} (ISC, see
// LICENSE-lucide.txt). Do not edit by hand: add names to names.json and re-run.
export const ICONS = {
${entries.join('\n')}
} as const

export type IconName = keyof typeof ICONS

export const LUCIDE_VERSION = ${JSON.stringify(version)}
`)
writeFileSync(join(out, 'LICENSE-lucide.txt'), readFileSync(join(pkg, 'LICENSE'), 'utf8'))
console.log(`wrote ${names.length} icons from lucide-static ${version}`)
